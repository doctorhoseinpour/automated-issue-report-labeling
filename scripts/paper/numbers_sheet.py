    P("")
    # cost
    tex = COST.read_text()
    rows = re.findall(r"^\s*(Qwen-\d+B|)\s*&\s*(\\\w+|Fine-Tune|Fine-tuning|[^&]+?)\s*&\s*([\d.]+)\s*&\s*"
                      r"([\d.]+|--)\s*&\s*([\d.]+|\$<\$0\.01)\s*&\s*([\d.]+|\$<\$0\.01)\s*\\\\", tex, re.M)
    cost, model = {}, None
    for mdl, meth, gb, tr, inf, tot in rows:
        model = mdl or model
        key = {"\\ragtag": "rag", "\\bragtag": "frag", "\\rag": "rag", "\\frag": "frag"}.get(meth, "ft")
        cost[(model, key)] = (float(gb), tr, inf, tot)
    P("Cost (`SANER2027/tables/method_cost.tex`; RAG memory is inference, fine-tuning memory is training plus "
      "inference):")
    P("")
    P("| Model | RAG GB | Filtered RAG GB | FT GB | Saving | RAG infer h | Filtered RAG infer h | FT train h | "
      "FT infer h | FT total h |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    savings = []
    for m in MODELS:
        r, f, t = cost[(m, "rag")], cost[(m, "frag")], cost[(m, "ft")]
        s = 1 - r[0] / t[0]
        savings.append(s)
        P(f"| {m} | {r[0]} | {f[0]} | {t[0]} | {100 * s:.0f}% ({100 * s:.1f}) | {r[2]} | {f[2]} | {t[1]} | "
          f"{t[2]} | {t[3]} |")
    P("")
    P(f"- Memory saving (from the GB values in the table): {'/'.join(f'{100 * s:.0f}' for s in savings)}%; mean "
      f"{share(mean(savings))}.")
    ft_inf = [float(cost[(m, 'ft')][2]) for m in MODELS]
    fr_inf = [float(cost[(m, 'frag')][2]) for m in MODELS]
    P(f"- Inference time: fine-tuned models {min(ft_inf):.2f}–{max(ft_inf):.2f} h; filtered RAG "
      f"{min(fr_inf):.2f}–{max(fr_inf):.2f} h. Totals: filtered RAG "
      f"{', '.join(cost[(m, 'frag')][3] for m in MODELS)} h vs fine-tuning "
      f"{', '.join(cost[(m, 'ft')][3] for m in MODELS)} h.")
    P("- kNN voting (PS, k = 15): 0.2 GB peak GPU memory (242.2 MB), under 4 s (3.58 s) for the 3,300 test "
      "issues (method_cost.tex header).")
    P("")


