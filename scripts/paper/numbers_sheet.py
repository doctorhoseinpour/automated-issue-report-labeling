# ---------------------------------------------------------------- formatting
def pct(x: float) -> str:
    """Score in percent, one decimal."""
    return f"{100 * x:.1f}"


def pts(d: float) -> str:
    """Difference in points, one decimal, signed (the sheet only; prose uses words)."""
    v = round(100 * d, 1)
    return f"{v:+.1f}".replace("+0.0", "0.0").replace("-0.0", "0.0").replace("-", "−")


def share(x: float) -> str:
    """Share or error rate: whole percent, exact one-decimal value in brackets."""
    return f"{100 * x:.0f}% ({100 * x:.1f})"


def rng(values, f=pct, unit="") -> str:
    """min-max over exact values, then rounded."""
    lo, hi = min(values), max(values)
    a, b = f(lo), f(hi)
    return (a if a == b else f"{a}–{b}") + unit


def srng(values) -> str:
    lo, hi = min(values), max(values)
    a, b = f"{100 * lo:.0f}", f"{100 * hi:.0f}"
    return (f"{a}%" if a == b else f"{a}–{b}%") + f" ({100 * lo:.1f}–{100 * hi:.1f})"


def prng(values) -> str:
    """Range of signed differences in points."""
    return rng(values, pts)


def mean(values):
    values = list(values)
    return sum(values) / len(values)


# ---------------------------------------------------------------- data access
cells = pd.read_csv(CELLS)
cells["kk"] = pd.to_numeric(cells.k.replace("-", "-1"), errors="coerce").astype(int)


def cell(method, setting, model, k=None):
    q = cells[(cells.method == method) & (cells.setting == setting) & (cells.model == model)]
    if k is not None:
        q = q[q.kk == k]
    assert len(q) == 1, (method, setting, model, k, len(q))
    return q.iloc[0]


def best(method, setting, model):
    """Highest macro F1 on the grid (same rule as tab_results_master.best_configs)."""
    q = cells[(cells.method == method) & (cells.setting == setting) & (cells.model == model)]
    return q.sort_values("f1_macro", ascending=False).iloc[0]


def zs(model):
    return cell("zero_shot", "PA", model)


def B(method, model):  # the configurations the paper compares
    setting = "PA" if method == "ftpa" else "PS"
    method = "finetune" if method in ("ftpa", "ftps") else method
    return best(method, setting, model)


def ftps(m): return best("finetune", "PS", m)
def ftpa(m): return best("finetune", "PA", m)
def rag(m): return best("ragtag", "PS", m)
def frag(m): return best("bragtag", "PS", m)


def kstr(r):
    return "–" if r.kk < 0 else str(r.kk)


