    P(f"- kNN voting PA > PS in macro F1 at {pa_higher} of {len(common)} evaluated k "
      f"(k = {common[0]}..{common[-1]} as in the grid).")
    q_lowest = all(min(r.f1_bug, r.f1_feature, r.f1_question) == r.f1_question
                   for _, r in cells[cells.method == "votag"].iterrows())
    bug_over = all(r.r_bug > r.p_bug for _, r in cells[cells.method == "votag"].iterrows())
    P(f"- kNN voting: question has the lowest class F1 at every k in both settings: {q_lowest}; "
      f"bug recall > bug precision at every k: {bug_over}.")
    P("- kNN voting: PS and PA share 84–90% of their top-k neighbors for k in 3..30 — **from the draft**.")
    P("")
