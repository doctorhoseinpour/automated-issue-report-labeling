"""SANER2027/tables/results_master.tex -- the single results table of Section V.

Rows: VOTAG (PS, PA) and, per Qwen size, zero-shot, RAGTAG (PS, best k), BRAGTAG
(PS, best k), Fine-Tune (PS), Fine-Tune (PA). Columns (author's order, 2026-09-22):
per-class precision and recall, then macro precision, macro recall and macro F1,
and the invalid rate last. The best macro F1 in each Qwen block is bold. Predicted
bug share and the question-to-bug rate stay in triangulation_all_cells.csv for the
prose. The macro F1 with the VOTAG fallback moved to Table II (author decision,
2026-09-22); --fallback-column restores it as a column before Invalid.

Inputs (both committed, so this runs on any machine):
  paper/tables/triangulation_all_cells.csv   (tab_triangulation.py, lab machine)
  paper/tables/fallback_macro_f1.csv         (fallback macro F1; see its header)
Convention: pooled over the 3,300 test issues; raw predictions unless stated.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from _figstyle import MODELS

REPO = Path(__file__).resolve().parents[2]
CELLS = REPO / "paper" / "tables" / "triangulation_all_cells.csv"
FALLBACK = REPO / "paper" / "tables" / "fallback_macro_f1.csv"
OUT = REPO / "SANER2027" / "tables" / "results_master.tex"

BLOCK = [  # method, setting, label
    ("zero_shot", "PA", "Zero-shot"),
    ("ragtag", "PS", "RAG (PS)"),
    ("bragtag", "PS", "Filtered RAG (PS)"),
    ("finetune", "PS", "Fine-tuning (PS)"),
    ("finetune", "PA", "Fine-tuning (PA)"),
]
FALLBACK_ROWS = {("ragtag", "PS"), ("bragtag", "PS"), ("finetune", "PA"), ("finetune", "PS")}


def f3(x): return f"{100 * x:.1f}"  # scores print in percent, one decimal
def fpct(x): return f"{100 * x:.1f}"


def best_configs(cells: pd.DataFrame) -> pd.DataFrame:
    return (cells.sort_values("f1_macro", ascending=False)
                 .groupby(["method", "setting", "model"], as_index=False).head(1))


def _row(best, fb, method, setting, model, label, first_cell, bold=False, fallback_col=False):
    r = best[(best.method == method) & (best.setting == setting) & (best.model == model)].iloc[0]
    k = "--" if str(r.k) == "-" else str(int(r.k))
    macro = r"\textbf{" + f3(r.f1_macro) + "}" if bold else f3(r.f1_macro)
    fallback = "--"
    if (method, setting) in FALLBACK_ROWS:
        q = fb[(fb.method == method) & (fb.setting == setting) & (fb.model == model)]
        if len(q) == 1:
            assert str(q.iloc[0].k) == str(r.k), (method, model, q.iloc[0].k, r.k)
            fallback = f3(q.iloc[0].f1_macro_fallback)
        elif fallback_col:  # not computed yet (Fine-Tune PS needs one tab_triangulation.py run on the lab machine)
            print(f"note: no fallback value for {method} {setting} {model}; printing --", file=sys.stderr)
    cells = [first_cell, label, k,
             f3(r.p_bug), f3(r.r_bug), f3(r.p_feature), f3(r.r_feature),
             f3(r.p_question), f3(r.r_question),
             f3(r.p_macro), f3(r.r_macro), macro] + ([fallback] if fallback_col else []) + [fpct(r.invalid_rate)]
    return "    " + " & ".join(cells) + r" \\"


def emit(best: pd.DataFrame, fb: pd.DataFrame, fallback_col: bool = False) -> str:
    fb_head = r"+ fallback & " if fallback_col else ""
    fb_sub = "& " if fallback_col else ""
    ncol = 14 if fallback_col else 13
    L = [
        "% Generated by scripts/paper/tab_results_master.py -- do not edit by hand.",
        r"\begin{table*}[!t]",
        r"  \centering",
        r"  \caption{Results (\%) of every method at its best configuration on all 3{,}300 test issues.}",
        r"  \label{tab:results}",
        r"  \footnotesize",
        # 0.97: the mildest row spacing that keeps the main text within ten pages (2026-09-22).
        r"  \renewcommand{\arraystretch}{0.97}",
        r"  \setlength{\tabcolsep}{6pt}",
        r"  \begin{tabular}{@{}ll" + "r" * (ncol - 2) + "@{}}",
        r"    \toprule",
        r"    Model & Method & $k$ & "
        r"\multicolumn{2}{c}{Bug} & \multicolumn{2}{c}{Feature} & \multicolumn{2}{c}{Question} & "
        r"$P_{\text{mac}}$ & $R_{\text{mac}}$ & Macro $F_1$ & " + fb_head + r"Invalid \\",
        r"    \cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        r"     & & & $P$ & $R$ & $P$ & $R$ & $P$ & $R$ & & & & " + fb_sub + r" \\",
        r"    \midrule",
        _row(best, fb, "votag", "PS", "-", r"$k$NN voting (PS)", "--", fallback_col=fallback_col),
        _row(best, fb, "votag", "PA", "-", r"$k$NN voting (PA)", "", fallback_col=fallback_col),
    ]
    for m in MODELS:
        L.append(r"    \midrule")
        block = best[(best.model == m) & best.method.isin(["zero_shot", "ragtag", "bragtag", "finetune"])]
        top = block.f1_macro.max()
        for i, (method, setting, label) in enumerate(BLOCK):
            r = block[(block.method == method) & (block.setting == setting)].iloc[0]
            L.append(_row(best, fb, method, setting, m, label, m if i == 0 else "",
                          bold=f3(r.f1_macro) == f3(top), fallback_col=fallback_col))
    L += [
        r"    \bottomrule",
        r"  \end{tabular}",
        # Note outside the tabular so the table keeps its natural width (a p{\textwidth}
        # note row would stretch the last column to fill the text width).
        r"  \par\vspace{2pt}",
        r"  \parbox{\textwidth}{\scriptsize "
        r"PS: 300 labeled issues of the target project; PA: the 3{,}300 issues of all eleven projects. "
        r"$P$/$R$: precision/recall; $P_{\text{mac}}$/$R_{\text{mac}}$: their macro averages. "
        r"Invalid outputs count as incorrect. "
        + (r"+ fallback: macro $F_1$ with the $k$NN voting fallback for invalid outputs ($k$NN voting PS at $k{=}15$ "
           r"for PS rows, PA at $k{=}16$ for PA rows). " if fallback_col else "")
        + r"Bold: best macro $F_1$ per model size.}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cells", type=Path, default=CELLS)
    ap.add_argument("--fallback", type=Path, default=FALLBACK)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--fallback-column", action="store_true",
                    help="restore the +VOTAG column (macro F1 with the VOTAG fallback)")
    args = ap.parse_args()
    best = best_configs(pd.read_csv(args.cells))
    fb = pd.read_csv(args.fallback, comment="#", dtype={"k": str})
    args.out.write_text(emit(best, fb, fallback_col=args.fallback_column))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
